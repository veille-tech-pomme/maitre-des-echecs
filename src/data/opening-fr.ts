const HEADS: [RegExp, string][] = [[/ Variation$/, 'variante'], [/ Countergambit$/, 'contre-gambit'], [/ Attack$/, 'attaque'], [/ Gambit$/, 'gambit'], [/ Defense$/, 'défense'], [/ Line$/, 'ligne'], [/ System$/, 'système'], [/ Opening$/, 'ouverture'], [/ Formation$/, 'formation'], [/ Trap$/, 'piège']];
function part(s: string): string {
  s = s.trim(); if (!s) return s;
  if (s === 'Main Line') return 'ligne principale';
  if (s.startsWith('with ')) return 'avec ' + s.slice(5).replace(/\b([NBRQK])(?=[a-h]?x?[a-h][1-8])/g, (m) => ({ N: 'C', B: 'F', R: 'T', Q: 'D', K: 'R' } as any)[m]);
  s = s.replace(/(\w)['’]s\b/g, '$1');
  for (const [re, fr] of HEADS) if (re.test(s)) { const rest = s.replace(re, ''); return `${fr} ${rest.split(' ').map((w) => WORD[w] || w).join(' ')}`.trim(); }
  return s.split(' ').map((w) => WORD[w] || w).join(' ');
}
/** « Sicilian Defense: Najdorf Variation, English Attack » → « Défense sicilienne : variante Najdorf, attaque anglaise ». */
export function openingFr(name: string): string {
  if (!name) return '';
  const n = name.replace(/_/g, ' ');
  const [fam, rest] = n.includes(':') ? [n.slice(0, n.indexOf(':')), n.slice(n.indexOf(':') + 1)] : [n, ''];
  const famParts = fam.split(','); const f0 = famParts[0].trim();
  const famFr = (FAMILY[f0] || part(f0)) + famParts.slice(1).map((p) => ', ' + part(p)).join('');
  if (!rest) return famFr;
  return famFr + ' : ' + rest.split(',').map(part).join(', ');
}
export const familyFr = (fam: string) => openingFr(fam.replace(/_/g, ' '));
